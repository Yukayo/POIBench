def tab_dataneeds(cfg, split, metric="ndcg@10"):
    conf = confirmatory(split)
    n = 1 + len(DN_POL) + 2
    L = [r"\scriptsize", r"\setlength{\tabcolsep}{2.2pt}", r"\begin{tabular}{@{}l" + "r" * (n - 1) + "@{}}", r"\toprule",
         " & ".join(["method"] + [rf"\textsf{{{p}}}" for p in DN_POL] + [r"$\Delta_H$", r"$\Delta_{HS}$"]) + r" \\"]
    lab = {m["pred"]: m["label"] for m in cfg["methods"]}
    for d in cfg["datasets"]:
        if d["ds"] not in cfg["dataneeds_datasets"]:
            continue
        res = R(d["ds"], split)
        L += [r"\midrule", rf"\multicolumn{{{n}}}{{@{{}}l}}{{\textit{{{d['label']}}}}}\\"]
        for p in cfg["dataneeds_methods"]:
            v = {pol: res.get(f"{p}@{pol}", metric) for pol in DN_POL}
            if all(v[pol] is None for pol in DN_POL if pol != "H-100") and p not in cfg.get("pending_rows", []):
                continue
            dh = None if v["H-10"] is None or v["H-100"] is None else v["H-10"] - v["H-100"]
            dhs = None if v["H-10"] is None or v["S-10"] is None else v["H-10"] - v["S-10"]

            def mk(b):
                c = conf.get(("Q2", d["ds"], f"{p}@H-10", f"{p}@{b}"))
                return r"$^{*}$" if c and c.get("reject_h0") == "True" else ""
            L.append(" & ".join([lab.get(p, p)] + [f4(v[pol]) for pol in DN_POL]
                                + [sf4(dh) + mk("H-100"), (sf4(dhs) + mk("S-10")) if p not in cfg["simple_preds"] else "="]) + r" \\")
