def isnum(x):
    return x is not None and not (isinstance(x, float) and math.isnan(x))


def f4(x, bold=False, mark=""):
    if not isnum(x):
        return DASH
    s = f"{x:.4f}"
    if s.startswith("-"):
        s = "$-$" + s[1:]
    if bold:
        s = r"\textbf{" + s + "}"
    return s + mark


def sf4(x):
    if not isnum(x):
        return DASH
    return ("+" if x >= 0 else "$-$") + f"{abs(x):.4f}"


def pct(x, nd=2, signed=False):
    if not isnum(x):
        return DASH
    s = f"{100 * abs(x) if signed else 100 * x:.{nd}f}\\%"
    if signed:
        s = ("+" if x >= 0 else "$-$") + s
    return s


def intc(x):
    return DASH if not isnum(x) else f"{int(x):,}".replace(",", "{,}")


def q2(x):
    if not isnum(x):
        return DASH
    if abs(x) >= 1000:
        return f"{x:,.0f}".replace(",", "{,}")
    return f"{x:.2f}"


