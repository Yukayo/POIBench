def tab_main(cfg, split):
    conf = confirmatory(split)
    dss = cfg["datasets"]
    blocks = [dss[i::3] for i in range(3)]
    blocks = [[dss[0], dss[3]], [dss[1], dss[4]], [dss[2], dss[5]]] if len(dss) == 6 else [dss[i:i + 2] for i in range(0, len(dss), 2)]
    nm = len(METRICS)
    ncol = 1 + 2 * nm
    L = [r"\scriptsize", r"\setlength{\tabcolsep}{2.1pt}",
         r"\begin{tabular}{@{}l" + "r" * nm + r"@{\hspace{7pt}}" + "r" * nm + "@{}}", r"\toprule"]
    for bi, blk in enumerate(blocks):
        if bi:
            L.append(r"\midrule")
        heads = []
        for d in blk:
            res = R(d["ds"], split)
            rc = res.recall.get("H-100")
            heads.append(rf"\multicolumn{{{nm}}}{{c}}{{\textbf{{{d['label']}}} ({intc(res.sizes.get('all'))} queries; "
                         rf"R@20 = {f4(rc)})}}")
        L.append(" & ".join([""] + heads) + r" \\")
        L.append("".join(rf"\cmidrule(lr){{{2 + i * nm}-{1 + (i + 1) * nm}}}" for i in range(len(blk))))
        L.append(" & ".join(["method"] + MHEAD * len(blk)) + r" \\")
        L.append(r"\midrule")
        best = {}
        for d in blk:
            res = R(d["ds"], split)
            for met in METRICS:
                vals = [res.get(f"{m['pred']}@{mpol(cfg, d['ds'], m['pred'])}", met) for m in cfg["methods"]]
                vals = [round(v, 4) for v in vals if v is not None]
                best[(d["ds"], met)] = max(vals) if vals else None
        prev_fam = None
        for m in cfg["methods"]:
            if prev_fam is not None and m["family"] != prev_fam:
                L.append(r"\addlinespace[1.5pt]")
            prev_fam = m["family"]
            cells = []
            for d in blk:
                res = R(d["ds"], split)
                name = f"{m['pred']}@{mpol(cfg, d['ds'], m['pred'])}"
                for met in METRICS:
                    v = res.get(name, met)
                    mk = holm_mark(conf, d["ds"], name) if met == "acc@1" and m["pred"] != REF else ""
                    cells.append(f4(v, bold=(v is not None and round(v, 4) == best[(d["ds"], met)]), mark=mk))
            L.append(" & ".join([m["label"]] + cells) + r" \\")
        crows = [c for c in cfg.get("completion_rows", [])
                 if any(R(d["ds"], split).get(f"{c['pred']}@H-100", "acc@1") is not None for d in blk)]
        if crows:
            L.append(r"\addlinespace[1.5pt]")
        for c in crows:
            cells = []
            for d in blk:
                res = R(d["ds"], split)
                for met in METRICS:
                    cells.append(f4(res.get(f"{c['pred']}@H-100", met)))
            L.append(" & ".join([r"\textit{" + c["label"] + "}"] + cells) + r" \\")
    L.append(draft_note(split, ncol))
    L += [r"\bottomrule", r"\end{tabular}"]
    write("tab_main", "\n".join(L) + "\n")


