def esc(s: str) -> str:
    return s.replace("_", r"\_")


def _fl(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return None if math.isnan(v) else v


class Results:

    def __init__(self, ds: str, split: str):
        self.rows, self.pairs, self.recall, self.sizes = {}, {}, {}, {}
        d = ROOT / "results" / ds / split
        files = [f for f in sorted(glob.glob(str(d / "paper_*.csv"))) if not f.endswith(".pairs.csv")]
        files.sort(key=lambda f: ("_vs_" in os.path.basename(f), f))
        for f in files:
            with open(f) as fh:
                for r in csv.DictReader(fh):
                    k = (r["method"], r["mode"], r["stratum"], r["metric"])
                    if k not in self.rows:
                        v = _fl(r["value"])
                        if v is None:
                            continue
                        self.rows[k] = {x: _fl(r[x]) for x in ("value", "ci_lo", "ci_hi")} | {"n": int(float(r["n_queries"] or 0))}
            pf = f[:-4] + ".pairs.csv"
            if os.path.exists(pf):
                with open(pf) as fh:
                    for r in csv.DictReader(fh):
                        k = (r["a"], r["b"], r["mode"], r["stratum"], r["metric"])
                        self.pairs.setdefault(k, {x: _fl(r[x]) for x in ("diff", "ci_lo", "ci_hi", "p_boot")})
            jf = f[:-4] + ".json"
            if os.path.exists(jf):
                j = json.load(open(jf))
                cfg = j.get("config", {})
                if not cfg.get("e2e_only") and cfg.get("policy"):
                    self.recall.setdefault(cfg["policy"], j.get("strata_info", {}).get("cand_recall"))
                if cfg.get("policy") == "H-100":
                    self.sizes = j.get("strata_sizes", {})

    def get(self, method, metric, mode="e2e", stratum="all"):
        r = self.rows.get((method, mode, stratum, metric))
        return None if r is None else r["value"]

    def ci(self, method, metric, mode="e2e", stratum="all"):
        r = self.rows.get((method, mode, stratum, metric))
        return (None, None) if r is None else (r["ci_lo"], r["ci_hi"])

    def pair(self, a, b, metric, mode="e2e", stratum="all"):
        p = self.pairs.get((a, b, mode, stratum, metric))
        if p is not None:
            return p
        p = self.pairs.get((b, a, mode, stratum, metric))
        if p is None:
            return None
        return {"diff": -p["diff"], "ci_lo": -p["ci_hi"], "ci_hi": -p["ci_lo"], "p_boot": p["p_boot"]}


_RES = {}


def R(ds, split) -> Results:
    if (ds, split) not in _RES:
        _RES[(ds, split)] = Results(ds, split)
    return _RES[(ds, split)]


def confirmatory(split):
    p = ROOT / "results" / f"confirmatory_{split}.csv"
    out = {}
    if p.exists():
        for r in csv.DictReader(open(p)):
            out[(r["family"], r["ds"], r["a"], r["b"])] = {k: (_fl(r[k]) if k in ("diff", "ci_lo", "ci_hi", "p_boot", "p_holm")
                                                                else r[k]) for k in r}
    a = ROOT / "results" / f"confirmatory_{split}_B100000.csv"
    if a.exists():
        for r in csv.DictReader(open(a)):
            k = (r["family"], r["ds"], r["a"], r["b"])
            if k in out and r.get("p_amend") not in (None, "", "nan"):
                out[k].update(p_boot=_fl(r["p_amend"]), p_holm=_fl(r["p_holm_amend"]), reject_h0=r["reject_amend"])
    return out


def holm_mark(conf, ds, a, b=f"{REF}@H-100"):
    c = conf.get(("Q1", ds, a, b))
    if not c or c.get("reject_h0") != "True" or c.get("diff") is None:
        return ""
    return r"\up" if c["diff"] > 0 else r"\dn"


def load_meta(ds):
    p = ROOT / "data" / ds / "meta.json"
    return json.load(open(p)) if p.exists() else None


def future_filter(ds):
    m = load_meta(ds) or {}
    if m.get("future_filter"):
        return m["future_filter"]
    card = ROOT / "data" / "DATA_CARD.md"
    if card.exists():
        for line in card.read_text().splitlines():
            mm = re.match(rf"\|\s*{re.escape(ds)}\s*\|\s*([\d,]+)\s*\|\s*([\d.]+)\s*\|\s*$", line)
            if mm:
                return {"catalog_venues_below_min_before_cutoff": int(mm.group(1).replace(",", "")),
                        "val_target_share_at_such_venues": float(mm.group(2))}
    return None


def load_cost(pred, policy, ds, splits=("val", "test")):
    mp = f"{pred}@{policy}"
    exc = {sp: ROOT / "results" / "cost_exclusive" / mp / ds / f"{sp}.cost.json" for sp in splits}
    source = "exclusive" if all(p.exists() for p in exc.values()) else "preds"
    recs, flags = {}, []
    for sp in splits:
        p = exc[sp] if source == "exclusive" else ROOT / "preds" / mp / ds / f"{sp}.cost.json"
        if p.exists():
            recs[sp] = json.load(open(p))
            flag = recs[sp].get("colocated")
            side = ROOT / "results" / "cost_colocation" / mp / ds / f"{sp}.colocation.json"
            if source == "preds" and flag is None and side.exists():
                flag = json.load(open(side)).get("colocated")
            flags.append(flag)
    if not recs:
        return None
    once, perq = {}, {}
    for sp, r in recs.items():
        for st in r.get("stages", []):
            if st.get("one_time"):
                once.setdefault(st["name"], st)
            else:
                perq.setdefault(sp, []).append(st)
    out = {"n": {sp: r.get("n_queries") for sp, r in recs.items()}, "hardware": next(iter(recs.values())).get("hardware"),
           "source": source,
           "colocated": True if any(f is True for f in flags) else (False if all(f is False for f in flags) else None)}
    agg = lambda sts, k: sum(float(s.get(k) or 0.0) for s in sts)
    o = list(once.values())
    out["once"] = {k: agg(o, k) for k in ("wall_s", "cpu_core_s", "gpu_s", "gpu_busy_s")}
    out["once_peak_mem"] = max([float(s.get("peak_mem_gb") or 0) for s in o] or [0])
    out["peak_gpu_mem"] = max([float(s.get("peak_gpu_mem_nvml_gb") or s.get("peak_gpu_mem_gb") or 0)
                               for s in o + sum(perq.values(), [])] or [0])
    out["perq"] = {}
    for sp, sts in perq.items():
        n = out["n"].get(sp) or 0
        out["perq"][sp] = {k: (agg(sts, k) / n if n else None) for k in ("wall_s", "cpu_core_s", "gpu_s", "gpu_busy_s")}
        out["perq"][sp]["peak_mem"] = max(float(s.get("peak_mem_gb") or 0) for s in sts)
    return out


def icpc(c_m, c_r, a_m, a_r, n, key):
    if None in (c_m, a_m, a_r) or a_m <= a_r:
        return None
    cr_once = c_r["once"][key] if c_r else 0.0
    cr_q = ((c_r["perq"].get("test") or {}).get(key) or 0.0) if c_r else 0.0
    cm_q = (c_m["perq"].get("test") or {}).get(key) or 0.0
    if n is None:
        return (cm_q - cr_q) / (a_m - a_r)
    return ((c_m["once"][key] - cr_once) + n * (cm_q - cr_q)) / (n * (a_m - a_r))


