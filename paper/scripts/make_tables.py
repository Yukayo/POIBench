def tab_canary(cfg):
    cc = cfg["canary"]
    agg = {}
    for f in sorted(glob.glob(str(ROOT / "logs" / "canary" / "*.json"))):
        base = os.path.basename(f)[:-5]
        parts = base.split("__")
        if len(parts) < 4 or any(re.search(s, parts[0]) for s in cc["skip"]):
            continue
        lab = next(((l, kind) for rx, l, kind in cc["labels"] if re.search(rx, parts[0])), None)
        if lab is None:
            continue
        try:
            j = json.load(open(f))
        except Exception:
            continue
        nm = j.get("n_mismatch", {})
        mism = max([int(v) for v in nm.values()] or [0]) if isinstance(nm, dict) else int(nm or 0)
        k = (lab[1], lab[0])
        a = agg.setdefault(k, {"cities": set(), "pols": set(), "mism": 0, "nq": 0, "runs": 0, "verdicts": set()})
        a["cities"].add(parts[1])
        a["pols"].add(parts[2])
        a["mism"] = max(a["mism"], mism)
        a["nq"] = max(a["nq"], int(j.get("n_queries") or 0))
        a["runs"] += 1
        a["verdicts"].add(j.get("result", "?"))
    L = [r"\scriptsize", r"\setlength{\tabcolsep}{3pt}", r"\begin{tabular}{@{}l r l r l@{}}", r"\toprule",
         r"adapter & runs & policies & max mism. & verdict \\", r"\midrule"]
    prev = None
    for (kind, lab), a in sorted(agg.items(), key=lambda kv: (kv[0][0] == "control", kv[0][1])):
        if prev == "adapter" and kind == "control":
            L.append(r"\midrule")
        prev = kind
        L.append(" & ".join([lab, str(a["runs"]), ", ".join(rf"\textsf{{{p}}}" for p in sorted(a["pols"])),
                             f"{a['mism']}/{a['nq']}", "/".join(sorted(a["verdicts"]))]) + r" \\")
    if not agg:
        L.append(r"\multicolumn{5}{c}{" + DASH + r"}\\")
    L += [r"\bottomrule", r"\end{tabular}"]
    write("tab_canary", "\n".join(L) + "\n")


