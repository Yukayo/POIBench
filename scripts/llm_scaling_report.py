#!/usr/bin/env python
import argparse
import glob
import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor

for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ.setdefault(_v, "2")
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import pandas as pd

from poibench import ROOT
from poibench import evaluate as ev

POL = "H-100"
REF = f"hybrid@{POL}"
DATASETS = ("nyc", "tky", "ca", "sin", "istanbul", "sao_paulo")
FAMILIES = [
    ("DS-LLM4POI (zero-shot, LCS)", "ds-llm4poi-lcs", "ds-llm4poi-lcs-",
     ["qwen2.5-3b", "qwen2.5-7b", "qwen2.5-14b", "qwen2.5-32b", "llama3.1-8b", "mistral-7b-v0.3"]),
    ("LLM4POI (full fine-tune)", "llm4poi", "llm4poi-",
     ["qwen2.5-1.5b", "qwen2.5-3b", "qwen2.5-7b", "llama3.1-8b"]),
    ("GNPR-SID (LoRA)", "gnpr-sid", "gnpr-sid-",
     ["qwen2.5-7b", "qwen2.5-14b", "qwen2.5-32b", "llama3-8b"]),
]
PRIMARY_KEY = {"ds-llm4poi-lcs": "qwen2.5-7b", "llm4poi": "qwen2.5-7b", "gnpr-sid": "llama3-8b"}
METRICS = ("acc@1", "acc@10", "ndcg@10", "mrr")
LABEL = {"qwen2.5-1.5b": "Qwen2.5-1.5B", "qwen2.5-3b": "Qwen2.5-3B", "qwen2.5-7b": "Qwen2.5-7B",
         "qwen2.5-14b": "Qwen2.5-14B", "qwen2.5-32b": "Qwen2.5-32B", "llama3.1-8b": "Llama-3.1-8B",
         "llama3-8b": "Llama-3-8B", "mistral-7b-v0.3": "Mistral-7B-v0.3"}


def method_name(primary, prefix, key):
    return f"{primary}@{POL}" if key == PRIMARY_KEY[primary] else f"{prefix}{key}@{POL}"


def available(ds, split):
    out = [REF]
    for _, primary, prefix, keys in FAMILIES:
        for k in keys:
            m = method_name(primary, prefix, k)
            if os.path.exists(os.path.join(ROOT, "preds", m, ds, f"{split}.parquet")):
                out.append(m)
    return out


def run_one(ds, split):
    ms = available(ds, split)
    res = ev.evaluate_files(ROOT, ds, split, ms, out_prefix=os.path.join(ROOT, "results", ds, split,
                                                                          f"scaling_{POL}"),
                            policy=POL, e2e_only=True, B=1000, seed=0, pairs="ref", ref=REF)
    return ds, split, ms, res["n_queries"]


def cost_of(m, ds):
    one, inf, parse = 0.0, 0.0, None
    seen_one = False
    for split in ("val", "test"):
        p = os.path.join(ROOT, "preds", m, ds, f"{split}.cost.json")
        if not os.path.exists(p):
            return None
        c = json.load(open(p))
        for s in c["stages"]:
            g = float(s.get("gpu_s") or 0) / 3600
            if s.get("one_time"):
                if not seen_one:
                    one += g
            else:
                inf += g
        seen_one = True
        if split == "test":
            pr = c.get("parse_rates") or c.get("extra", {}).get("parse_rates")
            if pr:
                parse = (pr.get("lenient_valid"), pr.get("strict_valid"))
            ps = c.get("pred_stats") or c.get("extra", {}).get("pred_stats")
            if ps and parse is None:
                parse = (ps.get("share_full_beam"), None)
    return dict(one_time_gpu_h=one, infer_gpu_h=inf, parse=parse)


def fmt(x, nd=4):
    return "–" if x is None or x != x else f"{x:.{nd}f}"


def report(splits):
    lines = ["# LLM scaling: backbone size and family (EXPLORATORY)", "",
             "Pre-registered in the pre-registration log 2026-11-03T05:30Z (and the re-plans logged after it). Protocol v1.0 is frozen,",
             "so everything here is exploratory (PROTOCOL 6.3): point estimates with 95% paired user-bootstrap CIs",
             "(B = 1000, seed 0, frozen evaluator), no hypothesis tests, no Holm family. Policy H-100, end-to-end",
             "ranking, seed 0, authors' hyperparameters; only the backbone changes. Generated by",
             "`scripts/llm_scaling_report.py` from results/<ds>/<split>/scaling_H-100.*.", ""]
    sp = os.path.join(ROOT, "reports", "LLM_SCALING_STATUS.md")
    if os.path.exists(sp):
        lines += [open(sp).read().rstrip("\n"), ""]
    def delta(df_pairs, m, met):
        q = df_pairs[(df_pairs["a"] == m) & (df_pairs["b"] == REF) & (df_pairs["mode"] == "e2e") &
                     (df_pairs["stratum"] == "all") & (df_pairs["metric"] == met)]
        return None if q.empty else (q["diff"].iloc[0], q["ci_lo"].iloc[0], q["ci_hi"].iloc[0])

    for split in splits:
        pr = {}
        for ds in DATASETS:
            pp = os.path.join(ROOT, "results", ds, split, f"scaling_{POL}.pairs.csv")
            if os.path.exists(pp):
                pr[ds] = pd.read_csv(pp)
        if not pr:
            continue
        for met, name in (("acc@1", "Acc@1"), ("ndcg@10", "NDCG@10")):
            lines += [f"## Summary ({split}): Δ{name} vs Hybrid, point [95% paired-bootstrap CI]", "",
                      "| family | backbone | " + " | ".join(pr) + " |", "|---|---|" + "---|" * len(pr)]
            for fam, primary, prefix, keys in FAMILIES:
                for k in keys:
                    m = method_name(primary, prefix, k)
                    cells = []
                    for ds, pdf in pr.items():
                        d_ = delta(pdf, m, met)
                        cells.append("–" if d_ is None else f"{d_[0]:+.4f} [{d_[1]:+.4f}, {d_[2]:+.4f}]")
                    if any(c != "–" for c in cells):
                        lines.append(f"| {fam} | {LABEL[k]}{' (primary)' if k == PRIMARY_KEY[primary] else ''} | "
                                     + " | ".join(cells) + " |")
            lines.append("")
    for split in splits:
        tabs = {}
        for ds in DATASETS:
            p = os.path.join(ROOT, "results", ds, split, f"scaling_{POL}.csv")
            if os.path.exists(p):
                tabs[ds] = (pd.read_csv(p), pd.read_csv(p.replace(".csv", ".pairs.csv"))
                            if os.path.exists(p.replace(".csv", ".pairs.csv")) else None)
        if not tabs:
            continue
        lines += [f"## {split} split", ""]
        for ds, (df, pairs) in tabs.items():
            d = df[(df["mode"] == "e2e") & (df["stratum"] == "all")]
            lines += [f"### {ds} ({split})", "",
                      "| family | backbone | Acc@1 | Acc@10 | NDCG@10 | MRR | ΔAcc@1 vs Hybrid [95% CI] | "
                      "ΔNDCG@10 vs Hybrid [95% CI] | one-time GPU-h | infer GPU-h (val+test) | valid answer lenient / strict (GNPR: full beam) |",
                      "|---|---|---|---|---|---|---|---|---|---|---|"]

            def row(fam, label, m):
                v = {r["metric"]: r["value"] for _, r in d[d["method"] == m].iterrows()}
                if not v:
                    return None
                dl = []
                for met in ("acc@1", "ndcg@10"):
                    if pairs is None or m == REF:
                        dl.append("–")
                        continue
                    q = pairs[(pairs["a"] == m) & (pairs["b"] == REF) & (pairs["mode"] == "e2e") &
                              (pairs["stratum"] == "all") & (pairs["metric"] == met)]
                    dl.append("–" if q.empty else
                              f"{q['diff'].iloc[0]:+.4f} [{q['ci_lo'].iloc[0]:+.4f}, {q['ci_hi'].iloc[0]:+.4f}]")
                c = cost_of(m, ds) if m != REF else None
                pr = c and c["parse"]
                return (f"| {fam} | {label} | " + " | ".join(fmt(v.get(x)) for x in METRICS) + f" | {dl[0]} | {dl[1]} | "
                        + (f"{c['one_time_gpu_h']:.2f} | {c['infer_gpu_h']:.2f} | " if c else "– | – | ")
                        + (f"{100 * pr[0]:.2f}%" + (f" / {100 * pr[1]:.2f}%" if pr[1] is not None else "") + " |"
                           if pr is not None else "– |"))
            r = row("simple", "Hybrid (repeat + Markov)", REF)
            if r:
                lines.append(r)
            for fam, primary, prefix, keys in FAMILIES:
                for k in keys:
                    m = method_name(primary, prefix, k)
                    r = row(fam, LABEL[k] + (" (primary)" if k == PRIMARY_KEY[primary] else ""), m)
                    if r:
                        lines.append(r)
            lines.append("")
    lines += ["## GPU-hours per backbone (sum over the cities that finished; val + test)", "",
              "DS-LLM4POI: one-time = the vLLM engine load (recorded only in the first city of a job). GNPR-SID: one-time = SID "
              "(the primary run's SID cost, carried over for the backbone rows) + LoRA SFT. LLM4POI: one-time = the "
              "full fine-tune on 2 GPUs.", "",
              "| family | backbone | cities | one-time GPU-h | inference GPU-h | total GPU-h |", "|---|---|---|---|---|---|"]
    for fam, primary, prefix, keys in FAMILIES:
        for k in keys:
            m = method_name(primary, prefix, k)
            cs = [(ds, cost_of(m, ds)) for ds in DATASETS]
            cs = [(ds, c) for ds, c in cs if c]
            if cs:
                one = sum(c["one_time_gpu_h"] for _, c in cs)
                inf = sum(c["infer_gpu_h"] for _, c in cs)
                lines.append(f"| {fam} | {LABEL[k]}{' (primary)' if k == PRIMARY_KEY[primary] else ''} | "
                             f"{', '.join(ds for ds, _ in cs)} | {one:.2f} | {inf:.2f} | {one + inf:.2f} |")
    lines.append("")
    out = os.path.join(ROOT, "reports", "LLM_SCALING.md")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"-> {os.path.relpath(out, ROOT)}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--splits", nargs="+", default=["val", "test"])
    ap.add_argument("--datasets", nargs="+", default=list(DATASETS))
    ap.add_argument("--jobs", type=int, default=6)
    ap.add_argument("--report-only", action="store_true")
    a = ap.parse_args()
    if not a.report_only:
        with ProcessPoolExecutor(a.jobs) as pool:
            futs = [pool.submit(run_one, ds, s) for ds in a.datasets for s in a.splits]
            for f in futs:
                ds, s, ms, nq = f.result()
                print(f"{ds}/{s}: {nq} queries, {len(ms)} methods: {ms}", flush=True)
    report(a.splits)


if __name__ == "__main__":
    main()
